from __future__ import annotations

from pathlib import Path
from typing import Any

from .config import AgentConfig
from .memory import AgentMemory
from .tools import ToolRegistry, build_default_tools


class WorkAgent:
    def __init__(self, config: AgentConfig) -> None:
        self.config = config
        self.memory = AgentMemory(config.memory_file)
        self.tools: ToolRegistry = build_default_tools(
            workspace_root=config.workspace_root,
            log_file=config.log_file,
        )

    def start(self) -> None:
        self.config.drive_root.mkdir(parents=True, exist_ok=True)
        self.config.log_file.parent.mkdir(parents=True, exist_ok=True)
        self.memory.load()

    def save(self) -> None:
        self.memory.save()

    def available_tools(self) -> list[str]:
        return self.tools.names()

    def handle_task(self, task: str) -> dict[str, Any]:
        result: dict[str, Any] = {
            "status": "planned",
            "message": "This starter agent records the task and exposes tools. Add a model planner next.",
            "suggested_next_steps": self._suggest_steps(task),
            "available_tools": self.available_tools(),
        }
        self.tools.run("append_log", message=f"TASK: {task}")
        self.memory.add_task_record(task, result)
        self.save()
        return result

    def create_text_project(self, relative_path: str, title: str) -> dict[str, str]:
        project_dir = Path(relative_path)
        readme = f"# {title}\n\nGenerated by the Colab work agent starter.\n"
        main_py = (
            "def main():\n"
            f"    print('Project: {title}')\n"
            "    print('This is the first generated project skeleton.')\n\n"
            "if __name__ == '__main__':\n"
            "    main()\n"
        )
        self.tools.run("write_file", path=str(project_dir / "README.md"), content=readme)
        self.tools.run("write_file", path=str(project_dir / "main.py"), content=main_py)
        output = self.tools.run("run_python", path=str(project_dir / "main.py"))
        return {"created": str(project_dir), "test_output": output}

    def create_html_game(self, relative_path: str, title: str) -> dict[str, str]:
        project_dir = Path(relative_path)
        html = self._html_game_template(title)
        readme = (
            f"# {title}\n\n"
            "A tiny browser game generated by the Colab work agent.\n\n"
            "Open `index.html` in a browser. Use the arrow keys or WASD to move.\n"
            "Collect yellow coins and avoid red hazards.\n"
        )
        self.tools.run("write_file", path=str(project_dir / "README.md"), content=readme)
        self.tools.run("write_file", path=str(project_dir / "index.html"), content=html)
        files = self.tools.run("list_dir", path=str(project_dir))
        return {"created": str(project_dir), "files": files}

    def _html_game_template(self, title: str) -> str:
        return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title}</title>
  <style>
    body {{
      margin: 0;
      min-height: 100vh;
      display: grid;
      place-items: center;
      background: #101820;
      color: #f7f7f7;
      font-family: Arial, sans-serif;
    }}
    main {{
      width: min(92vw, 760px);
    }}
    canvas {{
      width: 100%;
      aspect-ratio: 4 / 3;
      background: #1f2a34;
      border: 2px solid #415161;
      display: block;
    }}
    .hud {{
      display: flex;
      justify-content: space-between;
      align-items: center;
      margin: 12px 0;
      gap: 16px;
    }}
    button {{
      border: 0;
      border-radius: 6px;
      padding: 8px 12px;
      background: #f2c14e;
      color: #101820;
      font-weight: 700;
      cursor: pointer;
    }}
  </style>
</head>
<body>
  <main>
    <div class="hud">
      <strong>{title}</strong>
      <span id="status">Score: 0</span>
      <button id="restart">Restart</button>
    </div>
    <canvas id="game" width="640" height="480"></canvas>
  </main>
  <script>
    const canvas = document.querySelector("#game");
    const ctx = canvas.getContext("2d");
    const statusText = document.querySelector("#status");
    const restartButton = document.querySelector("#restart");
    const keys = new Set();

    let player;
    let coins;
    let hazards;
    let score;
    let gameOver;

    function reset() {{
      player = {{ x: 48, y: 48, size: 24, speed: 3 }};
      coins = [
        {{ x: 180, y: 90, size: 16 }},
        {{ x: 420, y: 120, size: 16 }},
        {{ x: 540, y: 360, size: 16 }},
        {{ x: 100, y: 390, size: 16 }}
      ];
      hazards = [
        {{ x: 260, y: 220, w: 120, h: 24, dx: 1.8 }},
        {{ x: 460, y: 250, w: 24, h: 120, dy: 1.4 }}
      ];
      score = 0;
      gameOver = false;
    }}

    function intersects(a, b) {{
      return a.x < b.x + (b.w || b.size) &&
        a.x + a.size > b.x &&
        a.y < b.y + (b.h || b.size) &&
        a.y + a.size > b.y;
    }}

    function update() {{
      if (gameOver) return;

      if (keys.has("ArrowLeft") || keys.has("a")) player.x -= player.speed;
      if (keys.has("ArrowRight") || keys.has("d")) player.x += player.speed;
      if (keys.has("ArrowUp") || keys.has("w")) player.y -= player.speed;
      if (keys.has("ArrowDown") || keys.has("s")) player.y += player.speed;

      player.x = Math.max(0, Math.min(canvas.width - player.size, player.x));
      player.y = Math.max(0, Math.min(canvas.height - player.size, player.y));

      for (const hazard of hazards) {{
        hazard.x += hazard.dx || 0;
        hazard.y += hazard.dy || 0;
        if (hazard.x < 0 || hazard.x + hazard.w > canvas.width) hazard.dx *= -1;
        if (hazard.y < 0 || hazard.y + hazard.h > canvas.height) hazard.dy *= -1;
        if (intersects(player, hazard)) gameOver = true;
      }}

      coins = coins.filter((coin) => {{
        if (intersects(player, coin)) {{
          score += 1;
          return false;
        }}
        return true;
      }});

      if (coins.length === 0) gameOver = true;
    }}

    function draw() {{
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      ctx.fillStyle = "#263847";
      ctx.fillRect(0, 0, canvas.width, canvas.height);

      ctx.fillStyle = "#f2c14e";
      for (const coin of coins) {{
        ctx.beginPath();
        ctx.arc(coin.x + coin.size / 2, coin.y + coin.size / 2, coin.size / 2, 0, Math.PI * 2);
        ctx.fill();
      }}

      ctx.fillStyle = "#d1495b";
      for (const hazard of hazards) ctx.fillRect(hazard.x, hazard.y, hazard.w, hazard.h);

      ctx.fillStyle = "#5bc0eb";
      ctx.fillRect(player.x, player.y, player.size, player.size);

      const message = coins.length === 0 ? "Won" : gameOver ? "Game over" : "Score";
      statusText.textContent = `${{message}}: ${{score}}`;
    }}

    function loop() {{
      update();
      draw();
      requestAnimationFrame(loop);
    }}

    addEventListener("keydown", (event) => keys.add(event.key));
    addEventListener("keyup", (event) => keys.delete(event.key));
    restartButton.addEventListener("click", reset);

    reset();
    loop();
  </script>
</body>
</html>
"""

    def _suggest_steps(self, task: str) -> list[str]:
        lowered = task.lower()
        if "game" in lowered or "spiel" in lowered:
            return [
                "Create a small project folder under projects/.",
                "Generate a minimal playable prototype.",
                "Run the prototype or tests.",
                "Save logs and next improvements.",
            ]
        if "map" in lowered or "karte" in lowered:
            return [
                "Define map format such as JSON, TMX, Godot, or Unity.",
                "Generate a small sample map.",
                "Validate the map structure.",
                "Save variants and notes.",
            ]
        return [
            "Clarify the output format.",
            "Create or update project files.",
            "Run validation.",
            "Persist result and log.",
        ]

